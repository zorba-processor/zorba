"""Merge QT3 shard results (qt3_run.py results.tsv files), write the report
and compare against the committed baseline of passing test cases.

Exit status is 1 if a test case listed in the baseline no longer passes
(a regression), 0 otherwise. Newly passing test cases are only reported.
"""

import argparse
import collections
import os
import sys
import xml.etree.ElementTree as ET

BASELINE_HEADER = """\
# W3C QT3 test cases (test-set/test-case) that pass with Zorba.
# .github/workflows/qt3.yml fails if one of them stops passing.
# Generated by test/fots/qt3_report.py (passing.txt in the qt3-report
# artifact) from qt3tests commit %s; replace the whole file to update.
"""


def area(test_set):
    return test_set.split("-", 1)[0]


def pct(n, d):
    return "%.1f%%" % (100.0 * n / d) if d else "-"


def row(counts):
    applicable = sum(counts[s] for s in ("pass", "fail", "wrongError", "error"))
    return [counts["pass"], counts["fail"], counts["wrongError"], counts["error"],
            counts["skip"], counts["n/a"], pct(counts["pass"], applicable)]


def table(header, rows):
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("results", nargs="+", help="results.tsv files")
    ap.add_argument("--baseline", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--summary", default="", help="markdown summary output")
    ap.add_argument("--qt3-commit", default="")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)

    res = {}
    for path in a.results:
        with open(path, encoding="utf-8") as f:
            for line in f:
                parts = line.rstrip("\n").split("\t")
                if len(parts) < 3:
                    continue
                s, c, st = parts[:3]
                res[(s, c)] = (st, parts[3] if len(parts) > 3 else "")

    baseline = set()
    if os.path.exists(a.baseline):
        with open(a.baseline) as f:
            baseline = {l.strip() for l in f if l.strip() and not l.startswith("#")}

    total = collections.Counter()
    by_area = collections.defaultdict(collections.Counter)
    by_set = collections.defaultdict(collections.Counter)
    for (s, c), (st, _) in res.items():
        total[st] += 1
        by_area[area(s)][st] += 1
        by_set[s][st] += 1

    key = lambda sc: "%s/%s" % sc
    passing = sorted(key(k) for k, (st, _) in res.items() if st == "pass")
    seen = {key(k) for k in res}
    passing_set = set(passing)
    regressions = sorted(k for k in baseline if k in seen and k not in passing_set)
    regressions_set = set(regressions)
    new_passes = sorted(k for k in passing if k not in baseline)
    missing = sorted(k for k in baseline if k not in seen)
    failing = sorted((key(k), st, det) for k, (st, det) in res.items()
                     if st in ("fail", "wrongError", "error"))

    with open(os.path.join(a.out, "passing.txt"), "w") as f:
        f.write(BASELINE_HEADER % (a.qt3_commit or "unknown"))
        f.write("".join(k + "\n" for k in passing))
    with open(os.path.join(a.out, "failing.tsv"), "w") as f:
        for k, st, det in failing:
            f.write("%s\t%s\t%s\n" % (k, st, det))
    with open(os.path.join(a.out, "not-applicable.tsv"), "w") as f:
        for k, (st, det) in sorted(res.items()):
            if st in ("n/a", "skip"):
                f.write("%s\t%s\t%s\n" % (key(k), st, det))
    with open(os.path.join(a.out, "regressions.txt"), "w") as f:
        f.write("".join(k + "\n" for k in regressions))
    with open(os.path.join(a.out, "new-passes.txt"), "w") as f:
        f.write("".join(k + "\n" for k in new_passes))

    # JUnit: one testsuite per test set; n/a and skip are <skipped/>.
    suites = ET.Element("testsuites", name="QT3")
    for s in sorted(by_set):
        cnt = by_set[s]
        ts = ET.SubElement(suites, "testsuite", name=s, tests=str(sum(cnt.values())),
                           failures=str(cnt["fail"] + cnt["wrongError"]),
                           errors=str(cnt["error"]),
                           skipped=str(cnt["skip"] + cnt["n/a"]))
        for (ss, c), (st, det) in sorted(res.items()):
            if ss != s:
                continue
            tc = ET.SubElement(ts, "testcase", classname=s, name=c)
            if st in ("fail", "wrongError"):
                ET.SubElement(tc, "failure", type=st, message=det)
            elif st == "error":
                ET.SubElement(tc, "error", message=det)
            elif st in ("skip", "n/a"):
                ET.SubElement(tc, "skipped", message="%s %s" % (st, det))
    ET.ElementTree(suites).write(os.path.join(a.out, "junit.xml"),
                                 encoding="utf-8", xml_declaration=True)

    applicable = sum(total[s] for s in ("pass", "fail", "wrongError", "error"))
    header = ["", "pass", "fail", "wrongError", "error", "skip", "n/a", "pass rate"]
    md = ["# W3C QT3 conformance (Zorba FOTS driver)", ""]
    if a.qt3_commit:
        md.append("qt3tests commit: `%s`" % a.qt3_commit)
        md.append("")
    md.append("**%d / %d applicable test cases pass (%s).** %d test cases in "
              "total; %d not applicable (n/a: unsupported spec version or "
              "feature per test/fots_driver/FOTSZorbaManifest.xml), %d skipped "
              "(EXPECTED_FOTS_FAILURE SLOW/CRASH, disputed). "
              "Pass rate = pass / (pass + fail + wrongError + error)."
              % (total["pass"], applicable, pct(total["pass"], applicable),
                 sum(total.values()), total["n/a"], total["skip"]))
    md.append("")
    if regressions:
        md.append("## :x: %d regression(s) against the baseline" % len(regressions))
        md.append("")
        for k in regressions[:50]:
            st, det = res[tuple(k.split("/", 1))]
            md.append("- `%s` %s %s" % (k, st, det[:200]))
        if len(regressions) > 50:
            md.append("- ... see regressions.txt")
        md.append("")
    else:
        md.append("No regressions against test/fots/qt3-baseline-pass.txt (%d cases)."
                  % len(baseline))
        md.append("")
    if new_passes:
        md.append("## %d newly passing test case(s)" % len(new_passes))
        md.append("")
        md.append("To update the baseline, replace test/fots/qt3-baseline-pass.txt "
                  "with `passing.txt` from the `qt3-report` artifact of this run "
                  "and commit it.")
        md.append("")
        for k in new_passes[:30]:
            md.append("- `%s`" % k)
        if len(new_passes) > 30:
            md.append("- ... see new-passes.txt")
        md.append("")
    if missing:
        md.append("%d baseline test case(s) were not run (filtered or removed "
                  "from the suite); they are not counted as regressions." % len(missing))
        md.append("")
    md.append("## By area")
    md.append("")
    rows = [[k] + row(by_area[k]) for k in sorted(by_area)]
    rows.append(["**total**"] + row(total))
    md.append(table(header, rows))
    md.append("")
    md.append("## By test set (sets with at least one non-passing applicable case)")
    md.append("")
    md.append("<details><summary>show</summary>")
    md.append("")
    rows = [[s] + row(by_set[s]) for s in sorted(by_set)
            if by_set[s]["fail"] + by_set[s]["wrongError"] + by_set[s]["error"]]
    md.append(table(["test set"] + header[1:], rows))
    md.append("")
    md.append("</details>")
    md.append("")
    text = "\n".join(md) + "\n"
    with open(os.path.join(a.out, "summary.md"), "w") as f:
        f.write(text)
    if a.summary:
        with open(a.summary, "a") as f:
            f.write(text)
    print("pass %d / applicable %d (%s); regressions %d; new passes %d"
          % (total["pass"], applicable, pct(total["pass"], applicable),
             len(regressions), len(new_passes)))
    return 1 if regressions_set else 0


if __name__ == "__main__":
    sys.exit(main())
