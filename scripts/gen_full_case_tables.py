"""Generate src/util/unicode_full_case.h, the full Unicode case mappings.

fn:upper-case and fn:lower-case use the full case mappings of the Unicode
Character Database (F&O 3.0 5.4.7/5.4.8): the simple mappings of
UnicodeData.txt plus the unconditional multi-character mappings of
SpecialCasing.txt (U+00DF -> "SS", U+0130 -> "i" + U+0307, ...). Python's
str.upper()/str.lower() implement exactly these for a single character, so
the tables come from the running Python's Unicode database; the version is
recorded in the generated header.

Usage:
  scripts/gen_full_case_tables.py > src/util/unicode_full_case.h
"""

